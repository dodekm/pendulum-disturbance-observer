function audit=review_identification_design(preview,baseline,controlRecords)
%REVIEW_IDENTIFICATION_DESIGN Offline conditional planning checks, not evidence.
assert(strcmp(preview.recording_kind,'synthetic')&&strcmp(baseline.recording_kind,'synthetic'));
assert(isequal(preview.theta,baseline.theta),'Compare inputs using the same nominal model.');
theta=preview.theta;items=cell(numel(controlRecords),1);
for k=1:numel(controlRecords)
    r=controlRecords{k};assert(strcmp(r.recording_kind,'synthetic'));
    mask=r.signals.read_valid&isfinite(r.signals.angle);y=rad2deg(r.signals.angle(mask));
    t=r.signals.t_device(mask);speed=diff(y)./diff(t);u=r.signals.u_command;
    items{k}=struct('protocol',r.metadata.experiment_id,'T',r.metadata.T, ...
        'use_compensation',r.metadata.use_compensation,'status',r.status.code, ...
        'angle_min_deg',min(y),'angle_max_deg',max(y), ...
        'command_min',min(u,[],'omitnan'),'command_max',max(u,[],'omitnan'), ...
        'min_secant_speed_deg_s',min(speed),'max_secant_speed_deg_s',max(speed));
end
control=vertcat(items{:});id=preview.cases;
coverage=struct('identification_angle_range_deg',[min([id.angle_min_deg]) max([id.angle_max_deg])], ...
    'control_angle_range_deg',[min([control.angle_min_deg]) max([control.angle_max_deg])], ...
    'identification_command_range',[min([id.command_min]) max([id.command_max])], ...
    'control_command_range',[min([control.command_min]) max([control.command_max])], ...
    'identification_secant_speed_range_deg_s',[min([id.min_secant_speed_deg_s]) max([id.max_secant_speed_deg_s])], ...
    'control_secant_speed_range_deg_s',[min([control.min_secant_speed_deg_s]) max([control.max_secant_speed_deg_s])], ...
    'seconds_near_30_45_60_deg',sum(vertcat(id.near_30_45_60_deg_seconds),1));
coverage.extrema_bracketed= ...
    coverage.identification_angle_range_deg(1)<=coverage.control_angle_range_deg(1)&& ...
    coverage.identification_angle_range_deg(2)>=coverage.control_angle_range_deg(2)&& ...
    coverage.identification_command_range(1)<=coverage.control_command_range(1)&& ...
    coverage.identification_command_range(2)>=coverage.control_command_range(2)&& ...
    coverage.identification_secant_speed_range_deg_s(1)<=coverage.control_secant_speed_range_deg_s(1)&& ...
    coverage.identification_secant_speed_range_deg_s(2)>=coverage.control_secant_speed_range_deg_s(2);
coverage.scope=['Necessary nominal extrema comparison only; not proof of joint state/input coverage, ', ...
    'physical safety, model adequacy, robust stability or validation on hardware.'];
stress=cell(8,1);
for k=0:7
    factors=1+.1*(2*bitget(k,1:3)-1);times=nan(1,numel(id));
    for j=1:numel(id)
        c=id(j);y=pendulumlab.simulate_output(theta.*factors,c.t,c.command,[0;0],4);
        first=find(abs(y)>=pi,1);if ~isempty(first),times(j)=c.t(first);end
    end
    stress{k+1}=struct('parameter_factors',factors,'first_180_degree_crossing_s',times, ...
        'crosses_180_degrees',isfinite(times));
end
audit=struct('schema_version','pendulumlab.identification_design_review/1', ...
    'recording_kind','synthetic','nominal_theta',theta, ...
    'nominal_plant_modes_hz',sqrt(theta(1)*cosd([0 30 45 60]))/(2*pi), ...
    'nominal_closed_loop_mode_hz',sqrt(25)/(2*pi), ...
    'observer_pole_frequencies_hz',1./(2*pi*[.2 .5 1]), ...
    'control_cases',control,'coverage',coverage, ...
    'baseline_information',information(baseline),'revised_information',information(preview), ...
    'illustrative_parameter_stress',vertcat(stress{:}), ...
    'stress_scope','Independent +/-10 percent parameter corners are illustrative scenarios, not confidence bounds or a certified uncertainty set.', ...
    'physical_readiness_established',false, ...
    'decision',['Use low/mid stages to check response and update the model before approving higher-angle stages. ', ...
    'Nominal high-angle coverage cannot authorize a physical open-loop experiment. ', ...
    'Freeze a fitted model and independent holdout protocol before model acceptance/control pilots.']);
end

function report=information(preview)
theta=preview.theta;J=[];
for k=1:numel(preview.cases)
    c=preview.cases(k);local=zeros(numel(c.t),3);
    for j=1:3
        plus=theta;minus=theta;plus(j)=plus(j)*exp(1e-4);minus(j)=minus(j)*exp(-1e-4);
        local(:,j)=(pendulumlab.simulate_output(plus,c.t,c.command,[0;0],4)- ...
            pendulumlab.simulate_output(minus,c.t,c.command,[0;0],4))/(2e-4);
    end
    nuisance=(pendulumlab.simulate_output(theta,c.t,c.command,[1e-3;0],4)- ...
        pendulumlab.simulate_output(theta,c.t,c.command,[-1e-3;0],4))/(2e-3);
    J=[J;local-nuisance*(nuisance\local)]; %#ok<AGROW>
end
singular=svd(J,0);assert(rank(J)==3,'Nominal design sensitivities do not have full numerical rank.');
[~,R]=qr(J,0);covariance=R\(R'\eye(3));
report=struct('profiled_log_parameter_singular_values',singular,'rank',rank(J), ...
    'condition',singular(1)/singular(end),'noise_scaled_log_parameter_std',sqrt(diag(covariance)), ...
    'definition',['Angle sensitivities to log(alpha,beta,gamma), with one initial-velocity ', ...
    'nuisance direction projected out per run; initial angle fixed.'], ...
    'scope',['Equal independent output-noise variance assumed for design comparison. ', ...
    'Noise-scaled standard deviations are conditional on this exact model, not measured uncertainty or confidence intervals.']);
end
