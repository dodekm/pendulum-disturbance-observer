function report = excitation_audit(cfg)
%EXCITATION_AUDIT Compare informative schedules on the historical nominal model.
% These are conditional planning diagnostics, never physical operating limits.
if nargin==0,cfg=pendulumlab.default_config('identification');end
names={'identification_multilevel','identification_prbs','identification_multisine'};
theta=cfg.theta(:)';step=1e-4;cases=cell(numel(names),1);
for k=1:numel(names)
    local=cfg;local.phase='identification';local.experiment_id=names{k};
    s=pendulumlab.make_schedule(local);
    y=pendulumlab.simulate_output(theta,s.t,s.command,[0;0],4);
    J=zeros(numel(y),3);
    for j=1:3
        plus=theta;minus=theta;plus(j)=theta(j)*exp(step);minus(j)=theta(j)*exp(-step);
        yp=pendulumlab.simulate_output(plus,s.t,s.command,[0;0],4);
        ym=pendulumlab.simulate_output(minus,s.t,s.command,[0;0],4);
        J(:,j)=(yp-ym)/(2*step);
    end
    singular=svd(J,0);gram=J'*J;
    norms=sqrt(diag(gram));corr=gram./max(norms*norms',realmin);
    entry=struct('protocol',names{k},'duration_s',s.duration_s, ...
        'command_min',min(s.command),'command_max',max(s.command), ...
        'command_slew_peak_units_s',max(abs(diff(s.command)))/cfg.Ts, ...
        'nominal_angle_peak_rad',max(abs(y)), ...
        'relative_parameter_singular_values',singular(:)', ...
        'sensitivity_condition',singular(1)/max(singular(end),realmin), ...
        'sensitivity_column_cosines',corr, ...
        'rank_at_machine_precision',rank(J));
    cases{k}=entry;
end
cases=vertcat(cases{:});
report=struct('schema_version','pendulumlab.excitation_audit/1', ...
    'theta_initial_guess',theta,'model_hardware_id',cfg.model_hardware_id, ...
    'planned_hardware_id',cfg.hardware_id,'recording_kind','synthetic', ...
    'sensitivity_definition','d(angle)/d(log(theta)); initial state fixed at rest', ...
    'cases',cases,'scope',['Nominal local sensitivities only. Initial-state uncertainty, ', ...
    'quantization, unknown propeller dynamics, timing and physical safety require independent checks. ', ...
    'Machine rank is not a physical identifiability certificate.']);
end
