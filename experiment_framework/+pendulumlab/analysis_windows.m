function windows=analysis_windows(cfg)
%ANALYSIS_WINDOWS Freeze evaluation intervals from the planned protocol only.
% Never select windows using measured performance.
n=numel(cfg.protocol.reference_levels_rad);dwell=cfg.protocol.plateau_s;
starts=(0:n-1)'*dwell;ends=starts+dwell;
hasCustomTracking=isfield(cfg.protocol,'reference_waypoints')||isfield(cfg.protocol,'reference_plateau_ranges_s');
if isfield(cfg.protocol,'reference_plateau_ranges_s')
    plateaus=cfg.protocol.reference_plateau_ranges_s;
    assert(isnumeric(plateaus)&&isreal(plateaus)&&ismatrix(plateaus)&&size(plateaus,2)==2&& ...
        size(plateaus,1)>=1&&all(isfinite(plateaus(:)))&&all(plateaus(:,1)>=0)&& ...
        all(plateaus(:,2)>plateaus(:,1))&&all(diff(plateaus(:,1))>=0)&& ...
        all(plateaus(1:end-1,2)<=plateaus(2:end,1))&& ...
        all(plateaus(:,2)<=cfg.protocol.duration_s), ...
        'pendulumlab:ReferencePlateaus','reference_plateau_ranges_s must be finite ordered [start_s,end_s] rows.');
    starts=plateaus(:,1);ends=plateaus(:,2);n=size(plateaus,1);
end
tail=cfg.analysis.tail_duration_s;
duration=n*dwell;
if hasCustomTracking,duration=cfg.protocol.duration_s;end
offset=0;
if strcmp(cfg.experiment_id,'injected_disturbance')
    duration=70;
    if isfield(cfg.protocol,'injection_time_offset_s')
        offset=cfg.protocol.injection_time_offset_s;
        assert(isnumeric(offset)&&isreal(offset)&&isscalar(offset)&&isfinite(offset)&&offset>=0, ...
            'pendulumlab:InjectionOffset','injection_time_offset_s must be finite and nonnegative.');
        duration=duration+offset;
    end
end
if startsWith(string(cfg.experiment_id),["identification_","validation_"])
    duration=cfg.protocol.duration_s;
end
if isfield(cfg.protocol,'startup_end_s')
    startupEnd=cfg.protocol.startup_end_s;
    assert(isnumeric(startupEnd)&&isreal(startupEnd)&&isscalar(startupEnd)&&isfinite(startupEnd)&& ...
        startupEnd>=0&&startupEnd<=duration,'pendulumlab:StartupWindow', ...
        'startup_end_s must lie between zero and the protocol duration.');
else
    startupEnd=min(10,duration);
end
windows=struct('tracking_full_s',[0 n*dwell], ...
    'tracking_plateaus_s',[starts ends], ...
    'tracking_tails_s',[max(starts,ends-tail) ends], ...
    'injection_full_s',[0 offset+70],'injection_pre_s',[offset+5 offset+10], ...
    'injection_positive_s',[offset+10 offset+20],'injection_negative_s',[offset+30 offset+40], ...
    'injection_random_s',[offset+50 offset+70], ...
    'injection_windows_s',[offset+10 offset+20;offset+30 offset+40;offset+50 offset+70], ...
    'injection_tails_s',[max(offset+10,offset+20-tail) offset+20; ...
        max(offset+30,offset+40-tail) offset+40], ...
    'startup_s',[0 startupEnd], ...
    'settling_error_rad',cfg.analysis.settling_error_rad, ...
    'settling_hold_s',cfg.analysis.settling_hold_s, ...
    'time_basis','nominal firmware sample grid; device/host timing retained for QC', ...
    'window_convention','left closed, right open', ...
    'definition_source','frozen planned schedule, not measured response');
windows.tracking_full_s=[0 durationForTracking(cfg,n,dwell)];
windows.tracking_plateaus_s=[starts ends];
windows.tracking_tails_s=[max(starts,ends-tail) ends];
if strcmp(cfg.experiment_id,'injected_disturbance')&&isfield(cfg.protocol,'injection_ramp_s')
    ramp=cfg.protocol.injection_ramp_s;
    assert(isscalar(ramp)&&isfinite(ramp)&&ramp>=cfg.Ts&&ramp<5,'pendulumlab:InjectionRamp', ...
        'Freeze an injection transition between one sample and less than five seconds.');
    windows.injection_positive_s(2)=windows.injection_positive_s(2)+ramp;
    windows.injection_negative_s(2)=windows.injection_negative_s(2)+ramp;
    windows.injection_windows_s(1:2,2)=windows.injection_windows_s(1:2,2)+ramp;
end
end

function duration=durationForTracking(cfg,n,dwell)
if strcmp(cfg.experiment_id,'reference_tracking')&& ...
        (isfield(cfg.protocol,'reference_waypoints')||isfield(cfg.protocol,'reference_plateau_ranges_s'))
    duration=cfg.protocol.duration_s;
else
    duration=n*dwell;
end
end
