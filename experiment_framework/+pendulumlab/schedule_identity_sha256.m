function digest=schedule_identity_sha256(schedule)
%SCHEDULE_IDENTITY_SHA256 Hash planned signal arrays, independent of run UUID.
identity=struct('name',char(schedule.name),'role',char(schedule.role), ...
    'seed',double(schedule.seed),'injection_seed',double(schedule.injection_seed), ...
    'duration_s',double(schedule.duration_s),'t',double(schedule.t(:)), ...
    'reference',double(schedule.reference(:)),'injection',double(schedule.injection(:)), ...
    'command',double(schedule.command(:)));
if isfield(schedule,'return_policy'),identity.return_policy=schedule.return_policy;end
text=jsonencode(identity);
md=java.security.MessageDigest.getInstance('SHA-256'); md.update(uint8(unicode2native(text,'UTF-8')));
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[]));
end
