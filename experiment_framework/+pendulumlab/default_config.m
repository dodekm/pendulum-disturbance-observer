function cfg = default_config(phase)
%DEFAULT_CONFIG Offline defaults; 180-degree cutoff, other physical gates unset.
arguments
    phase (1,1) string = "identification"
end
assert(any(phase==["identification","validation","pilot","confirmatory"]), ...
    'pendulumlab:Phase','Unknown experimental phase.');
root=pendulumlab.project_root();
cfg=struct;
cfg.schema_version='pendulumlab.config/1';
cfg.mode='mock'; cfg.phase=char(phase);
cfg.experiment_id='identification_multilevel';
if phase=="validation", cfg.experiment_id='validation_multisine'; end
if any(phase==["pilot","confirmatory"]), cfg.experiment_id='reference_tracking'; end
cfg.Ts=0.05; cfg.theta=[49.3401 0.4569 0.5586];
cfg.model_id='legacy_original_theta'; cfg.model_status='historical';
cfg.model_hardware_id='original_propeller'; cfg.model_record=struct;
cfg.model_registry_dir=fullfile(root,'experiment_framework','model_registry');
cfg.hardware_id='replacement_propeller_01';
cfg.a=25; cfg.T=0.5; cfg.use_compensation=false;
cfg.u_limits=[0 100]; cfg.source_root=root;
cfg.campaign_id=''; cfg.run_id=''; cfg.block_id=''; cfg.session_id=''; cfg.trial_id=1;
cfg.output_dir=fullfile(root,'experiment_framework','verification','synthetic_runs');
cfg.rng_seed=1; cfg.order_seed=811; cfg.integration_substeps=4;
cfg.protocol=struct('duration_s',120,'bias_command',25,'amplitude_command',7, ...
    'baseline_s',5,'ramp_s',15,'dwell_s',2.5,'seed',17, ...
    'reference_levels_rad',deg2rad([30 45 60 45 30]),'plateau_s',25, ...
    'injection_amplitude',5,'operator_excitation_approved',false, ...
    'multisine_hz',[0.08 0.16 0.32 0.56 0.8], ...
    'operating_envelope_approved',false);
% Synthetic schedules demonstrate software behavior, not a safe physical envelope.
cfg.safety=struct('max_abs_angle_rad',pi,'max_slew_units_s',NaN, ...
    'max_duration_s',180,'max_device_gap_s',0.075,'max_host_cycle_s',0.15, ...
    'rest_samples',30,'rest_range_rad',deg2rad(0.6),'rest_slope_rad_s',deg2rad(0.2));
cfg.hardware=struct('enabled',false,'operator_armed',false, ...
    'mechanical_ready',false,'angle_zero_confirmed',false,'model_accepted',false, ...
    'COM_port',4,'baudrate',250000,'stream_id',1,'read_timeout_ms',150, ...
    'write_timeout_ms',150);
cfg.mock=struct('theta',cfg.theta,'x0',[0;0],'noise_std_rad',0, ...
    'quantization_rad',0,'seed',29,'fault','none','fault_at',50, ...
    'disturbance',0,'hardware_id','synthetic_model');
cfg.replay=struct('file','','allow_control_claims',false);
cfg.checkpoint_samples=100;
cfg.campaign=struct('plan','core','intertrial_recovery_s',NaN, ...
    'max_physical_runs_per_invocation',1, ...
    'identification_bias_commands',[],'validation_bias_commands',[]);
cfg.analysis=struct('primary_tracking','full_record_rmse', ...
    'primary_injection','injection_window_rmse','tail_duration_s',3, ...
    'settling_error_rad',deg2rad(2),'settling_hold_s',5);
cfg.analysis.evaluation_windows=pendulumlab.analysis_windows(cfg);
end
