function characterized=accept_characterized_model(candidate,validation,options)
%ACCEPT_CHARACTERIZED_MODEL Record limited use after explicitly acknowledged failure.
% This route never promotes a model to validated/control-accepted status.
assert(isstruct(options)&&isfield(options,'registry_dir')&&isfield(options,'approval'), ...
    'pendulumlab:CharacterizedOptions','Provide registry_dir and explicit approval.');
assert(isfield(candidate,'status')&&strcmp(candidate.status,'candidate'), ...
    'pendulumlab:CandidateStatus','Only a candidate can be accepted for characterized experiments.');
assert(isfield(candidate,'fit')&&isfield(candidate.fit,'converged')&&candidate.fit.converged&&candidate.fit.exitflag>0, ...
    'pendulumlab:FitNotConverged','A converged parameter fit is required.');
assert(isfield(validation,'include')&&isfield(validation,'hardware_id'), ...
    'pendulumlab:Validation','Malformed validation record.');
v=validation.include;
assert(isfield(v,'criteria_frozen')&&isequal(v.criteria_frozen,true)&&isfield(v,'passed')&&isequal(v.passed,false), ...
    'pendulumlab:ValidationStatus','This route requires frozen validation that failed its accuracy criteria.');
assert(isfield(validation,'criteria')&&isfield(validation,'criteria_sha256')&& ...
    strcmpi(localHash(validation.criteria),validation.criteria_sha256), ...
    'pendulumlab:CriteriaHash','Frozen criteria digest mismatch.');
copy=validation;copy.include.report_hash='';
assert(isfield(v,'report_hash')&&strcmpi(localHash(copy),v.report_hash), ...
    'pendulumlab:ReportHash','Validation report digest mismatch.');
assert(isfield(validation,'candidate_theta_sha256')&& ...
    strcmpi(localHash(candidate.theta),validation.candidate_theta_sha256)&&isequal(double(candidate.theta(:)),double(validation.candidate_theta(:))), ...
    'pendulumlab:ThetaMismatch','Validation must bind exactly to candidate theta.');
assert(isfield(validation,'candidate_model_descriptor_sha256')&& ...
    strcmp(validation.candidate_model_descriptor_sha256,pendulumlab.model_descriptor_sha256(candidate)), ...
    'pendulumlab:DescriptorMismatch','Validation must bind the complete model and input descriptor.');
requiredChecks={'complete_frozen_plan','preacquisition_candidate_and_criteria_binding','max_substep_doubling_rad'};
assert(isfield(validation,'criteria_evaluation')&&all(isfield(validation.criteria_evaluation,requiredChecks))&& ...
    all(arrayfun(@(k)isequal(validation.criteria_evaluation.(requiredChecks{k}),true),1:numel(requiredChecks))), ...
    'pendulumlab:ValidationQuality','The complete frozen plan, preacquisition binding, and numerical convergence criterion must pass.');
assert(isfield(validation,'physical_promotion_eligible')&&isequal(validation.physical_promotion_eligible,true), ...
    'pendulumlab:ValidationKind','Physical complete-run evidence is required.');
assert(isfield(candidate,'training')&&all(isfield(candidate.training, ...
    {'run_ids','raw_hashes','signal_sha256','recording_kinds','hardware_ids','raw_hash_sha256','source_files_verified','status_codes'})), ...
    'pendulumlab:TrainingKind','Training provenance is incomplete.');
assert(~isempty(candidate.training.run_ids)&&~isempty(v.run_ids)&& ...
    numel(string(candidate.training.run_ids))==numel(string(candidate.training.raw_hashes))&& ...
    numel(string(v.run_ids))==numel(string(v.raw_hashes))&&all(strlength(string(candidate.training.raw_hashes))==64)&& ...
    all(strlength(string(v.raw_hashes))==64), 'pendulumlab:EmptyEvidence','Run IDs and SHA-256 hashes are required.');
localVerifyCandidate(candidate);
assert(strcmp(candidate.hardware_id,validation.hardware_id)&&all(string(v.hardware_ids)==string(candidate.hardware_id)), ...
    'pendulumlab:HardwareMismatch','Validation hardware differs from candidate.');
assert(all(string(candidate.training.hardware_ids)==string(candidate.hardware_id))&& ...
    all(string(candidate.training.recording_kinds)=="physical")&&all(candidate.training.raw_hash_sha256)&& ...
    all(candidate.training.source_files_verified)&&all(string(candidate.training.status_codes)=="completed"), ...
    'pendulumlab:TrainingKind','Physical completed training with verified source files is required.');
assert(all(string(v.recording_kinds)=="physical")&&all(v.raw_hashes_sha256)&& ...
    all(v.source_files_verified)&&all(string(v.status_codes)=="completed"), ...
    'pendulumlab:ValidationKind','Fresh physical completed holdouts with verified source files are required.');
assert(isempty(intersect(string(candidate.training.run_ids),string(v.run_ids)))&& ...
    isempty(intersect(string(candidate.training.raw_hashes),string(v.raw_hashes)))&& ...
    isempty(intersect(string(candidate.training.signal_sha256),string(v.signal_sha256))), ...
    'pendulumlab:ValidationLeakage','Training and holdout IDs, raw hashes, and signal hashes must be disjoint.');
a=options.approval;
required={'name','timestamp','reason','model_use_accepted','acknowledge_accuracy_failure','accepted_for_characterized_experiments', ...
    'accepted_for_control','accuracy_validation_passed','validated_angle_range_rad','validated_command_range'};
assert(all(isfield(a,required))&&isequal(string(a.name),"Martin Dodek")&& ...
    isequal(a.model_use_accepted,true)&&isequal(a.acknowledge_accuracy_failure,true)&&isequal(a.accepted_for_characterized_experiments,true)&& ...
    isequal(a.accepted_for_control,false)&&isequal(a.accuracy_validation_passed,false)&& ...
    strlength(string(a.reason))>0, 'pendulumlab:CharacterizedAcknowledgment', ...
    'Require Martin Dodek''s named model-use acknowledgment, reason, characterized-use acceptance, and explicit non-control/failed-accuracy flags.');
try,at=pendulumlab.parse_utc(a.timestamp);assert(at<=datetime('now','TimeZone','UTC')); ...
catch,error('pendulumlab:CharacterizedAcknowledgment','Timestamp must be valid UTC and not future dated.');end
domainCfg=struct('experiment_id','reference_tracking','protocol',struct('reference_levels_rad',[]), ...
    'u_limits',a.validated_command_range);
domainIssues=pendulumlab.validated_domain_issues(domainCfg,struct('approval',a,'validation',v));
assert(isempty(domainIssues),'pendulumlab:ValidationDomain','%s',strjoin(domainIssues,'; '));
characterized=struct('schema_version','pendulumlab.model_record/1','model_id',[char(candidate.model_id) '_characterized'], ...
    'status','characterized','theta',candidate.theta,'hardware_id',candidate.hardware_id,'candidate_id',candidate.model_id, ...
    'training',candidate.training,'candidate_registry_file_hash',candidate.registry_file_hash, ...
    'validation_report',validation, ...
    'validation',validation.include,'validation_summary',validation.summary,'validation_criteria',validation.criteria, ...
    'validation_criteria_sha256',validation.criteria_sha256,'accuracy_validation_passed',false, ...
    'characterized_use_scope','Empirical characterized experiments only; accuracy criteria failed; not validated for control.', ...
    'approval',a,'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
for key={'actuator_calibration','plant_characterization','nominal_inverse_scope'}
    if isfield(candidate,key{1}),characterized.(key{1})=candidate.(key{1});end
end
pendulumlab.save_model(characterized,string(options.registry_dir));
end
function h=localHash(s),h=pendulumlab.json_integrity_sha256(s);end
function localVerifyCandidate(c)
assert(isfield(c,'registry_file_hash')&&isfield(c,'registry_path')&& ...
    strcmpi(pendulumlab.file_hash(c.registry_path),c.registry_file_hash), ...
    'pendulumlab:CandidateHash','Candidate must be loaded from its hash-verified registry file.');
saved=jsondecode(fileread(c.registry_path));
assert(strcmp(saved.model_id,c.model_id)&&strcmp(saved.status,'candidate')&& ...
    isequal(double(saved.theta(:)),double(c.theta(:)))&&strcmp(saved.hardware_id,c.hardware_id)&& ...
    isequal(double(saved.fit.rmse_rad),double(c.fit.rmse_rad))&&saved.fit.exitflag==c.fit.exitflag, ...
    'pendulumlab:CandidateHash','In-memory candidate differs from persisted candidate.');
assert(strcmp(pendulumlab.model_descriptor_sha256(c),pendulumlab.model_descriptor_sha256(saved)), ...
    'pendulumlab:CandidateHash','Persisted model descriptor differs.');
for f={'run_ids','raw_hashes','source_files','source_files_verified','raw_hash_sha256','signal_sha256','recording_kinds','hardware_ids','status_codes'}
    assert(isequal(string(saved.training.(f{1})(:)),string(c.training.(f{1})(:))), ...
        'pendulumlab:CandidateHash','Persisted training provenance differs (%s).',f{1});
end
end
