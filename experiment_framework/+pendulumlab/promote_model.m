function promoted = promote_model(candidate,validation,options)
%PROMOTE_MODEL Immutable validated registry record behind physical evidence gates.
assert(isfield(options,'registry_dir')&&isfield(options,'approval'),'pendulumlab:PromotionOptions','Provide registry_dir and approval in options.');
assert(isfield(candidate,'status')&&strcmp(candidate.status,'candidate'),'pendulumlab:CandidateStatus','Only a candidate can be promoted.');
assert(isfield(candidate,'fit')&&isfield(candidate.fit,'converged')&&candidate.fit.converged&&candidate.fit.exitflag>0, ...
 'pendulumlab:FitNotConverged','A converged parameter fit is required for promotion.');
assert(isfield(validation,'include')&&isfield(validation,'hardware_id'),'pendulumlab:Validation','Malformed validation record.');v=validation.include;
assert(isfield(v,'criteria_frozen')&&isequal(v.criteria_frozen,true)&&isfield(v,'passed')&&isequal(v.passed,true), ...
 'pendulumlab:ValidationFailed','Promotion requires verifiably frozen criteria with passed=true.');
assert(isfield(validation,'criteria')&&isfield(validation,'criteria_sha256')&&strcmpi(localHash(validation.criteria),validation.criteria_sha256), ...
 'pendulumlab:CriteriaHash','Frozen criteria digest mismatch.');
copy=validation;copy.include.report_hash='';assert(strcmpi(localHash(copy),v.report_hash), ...
 'pendulumlab:ReportHash','Validation report digest mismatch.');
assert(isfield(validation,'candidate_theta_sha256')&&strcmpi(localHash(candidate.theta),validation.candidate_theta_sha256)&& ...
 isequal(double(candidate.theta(:)),double(validation.candidate_theta(:))),'pendulumlab:ThetaMismatch','Validation must bind exactly to candidate theta.');
assert(isfield(validation,'physical_promotion_eligible')&&validation.physical_promotion_eligible, ...
 'pendulumlab:ValidationKind','Validation is diagnostic only; physical complete-run hashes are required.');
assert(~isempty(candidate.training.run_ids)&&~isempty(v.run_ids)&&numel(string(candidate.training.run_ids))==numel(string(candidate.training.raw_hashes))&& ...
 numel(string(v.run_ids))==numel(string(v.raw_hashes))&&all(strlength(string(candidate.training.raw_hashes))==64)&&all(strlength(string(v.raw_hashes))==64), ...
 'pendulumlab:EmptyEvidence','Nonempty, one-to-one run IDs and verified raw hashes are mandatory.');
localVerifyCandidate(candidate);
if isfield(candidate,'actuator_calibration')||isfield(candidate,'plant_characterization')
    assert(isfield(validation,'candidate_model_descriptor_sha256')&& ...
        strcmp(validation.candidate_model_descriptor_sha256,pendulumlab.model_descriptor_sha256(candidate)), ...
        'pendulumlab:DescriptorMismatch','Validation must bind the complete physical model and input calibration.');
end
assert(strcmp(candidate.hardware_id,validation.hardware_id)&&all(string(v.hardware_ids)==string(candidate.hardware_id)), ...
 'pendulumlab:HardwareMismatch','Validation hardware differs from candidate.');
assert(all(string(candidate.training.hardware_ids)==string(candidate.hardware_id))&& ...
 all(string(candidate.training.recording_kinds)=="physical")&&all(candidate.training.raw_hash_sha256)&& ...
 all(candidate.training.source_files_verified)&&all(string(candidate.training.status_codes)=="completed"), ...
 'pendulumlab:TrainingKind','Physical training with complete statuses and SHA-256 provenance is required.');
assert(all(string(v.recording_kinds)=="physical")&&all(v.raw_hashes_sha256)&&all(v.source_files_verified)&& ...
 all(string(v.status_codes)=="completed"), ...
 'pendulumlab:ValidationKind','Physical validation with completed statuses and SHA-256 provenance is required.');
assert(isempty(intersect(string(candidate.training.run_ids),string(v.run_ids)))&& ...
 isempty(intersect(string(candidate.training.raw_hashes),string(v.raw_hashes)))&& ...
 isempty(intersect(string(candidate.training.signal_sha256),string(v.signal_sha256))), ...
 'pendulumlab:ValidationLeakage','Training/validation run IDs and hashes must be disjoint.');
a=options.approval;assert(isfield(a,'accepted_for_control')&&isequal(a.accepted_for_control,true)&& ...
 isfield(a,'name')&&strlength(string(a.name))>0&&isfield(a,'timestamp')&&strlength(string(a.timestamp))>0, ...
 'pendulumlab:HumanApproval','Explicit named, timestamped human control acceptance is required.');
try,at=pendulumlab.parse_utc(a.timestamp);assert(at<=datetime('now','TimeZone','UTC'));catch,error('pendulumlab:HumanApproval','Approval timestamp must be parseable UTC and not future dated.');end
assert(all(isfield(a,{'validated_angle_range_rad','validated_command_range'})), ...
 'pendulumlab:ValidationDomain','Human acceptance must specify validated angle and command ranges.');
domainCfg=struct('experiment_id','reference_tracking','protocol',struct('reference_levels_rad',[]),'u_limits',a.validated_command_range);
domainIssues=pendulumlab.validated_domain_issues(domainCfg,struct('approval',a,'validation',v));
assert(isempty(domainIssues),'pendulumlab:ValidationDomain','%s',strjoin(domainIssues,'; '));
promoted=struct('schema_version','pendulumlab.model_record/1','model_id',[char(candidate.model_id) '_validated'], ...
 'status','validated','theta',candidate.theta,'hardware_id',candidate.hardware_id,'candidate_id',candidate.model_id, ...
 'training',candidate.training,'candidate_registry_file_hash',candidate.registry_file_hash,'validation',validation.include,'validation_summary',validation.summary, ...
 'validation_criteria',validation.criteria,'validation_criteria_sha256',validation.criteria_sha256, ...
 'approval',a,'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss''Z''')));
for key={'actuator_calibration','plant_characterization','nominal_inverse_scope'}
    if isfield(candidate,key{1}),promoted.(key{1})=candidate.(key{1});end
end
pendulumlab.save_model(promoted,string(options.registry_dir));
end
