function localVerifyCandidate(c)
assert(isfield(c,'registry_file_hash')&&isfield(c,'registry_path')&&strcmpi(pendulumlab.file_hash(c.registry_path),c.registry_file_hash), ...
 'pendulumlab:CandidateHash','Promote only a candidate reloaded from its hash-verified immutable registry file.');
saved=jsondecode(fileread(c.registry_path));assert(strcmp(saved.model_id,c.model_id)&&strcmp(saved.status,'candidate')&& ...
 isequal(double(saved.theta(:)),double(c.theta(:)))&&strcmp(saved.hardware_id,c.hardware_id)&& ...
 isequal(double(saved.fit.rmse_rad),double(c.fit.rmse_rad))&&saved.fit.exitflag==c.fit.exitflag,'pendulumlab:CandidateHash','In-memory model fields differ from persisted candidate.');
assert(strcmp(pendulumlab.model_descriptor_sha256(c),pendulumlab.model_descriptor_sha256(saved)), ...
    'pendulumlab:CandidateHash','Persisted model/calibration descriptor differs.');
for f={'run_ids','raw_hashes','source_files','source_files_verified','raw_hash_sha256','signal_sha256','recording_kinds','hardware_ids','status_codes'}
 assert(isequal(string(saved.training.(f{1})(:)),string(c.training.(f{1})(:))),'pendulumlab:CandidateHash','Persisted training provenance differs (%s).',f{1});end
end
